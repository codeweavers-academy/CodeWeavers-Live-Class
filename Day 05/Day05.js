// Compound assignment operators

// Addition assignment (+=)
let marks = 50;
marks = marks + 10; // marks is now 60

marks += 10; // marks is now 70

console.log("1 addition assignment: " + marks);


marks =+ 10; // marks is now 80
console.log(" 2 After addition assignment: " + marks);

// Subtraction assignment (-=)
marks -= 20; // marks is now 60 -> marks = marks - 20
console.log("Subtraction assignment: " + marks);   

// Multiplication assignment (*=)
marks *= 2; // marks is now 120 - marks = marks * 2
console.log("Multiplication assignment: " + marks);

// Division assignment (/=)
marks /= 4; // marks is now 30 - marks = marks / 4
console.log("Division assignment: " + marks);

// Modulus assignment (%=)
marks %= 7; // marks is now 2 - marks = marks % 7
console.log("Modulus assignment: " + marks);

// Increment assignment (++)
marks++; // marks is now 3 - marks = marks + 1
console.log("Increment assignment: " + marks);

// Decrement assignment (--)
marks--; // marks is now 2 - marks = marks - 1
console.log("Decrement assignment: " + marks);




